"""Generate P1 exact-build sites from accepted evidence, without a new binary analysis."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
SOURCE = 'docs/evidence/m1/NATIVE_VISUAL_PROXY_58A/COMPLETION/GATE_N58A_C02/SITES.json'
sites = json.loads((ROOT / SOURCE).read_text(encoding='utf8'))
names = ['factory', 'remove', 'interpolant_reset', 'point_in_sector', 'floor_height', 'ceiling_height',
         'puppet_tick', 'actor_tick', 'on_remove', 'pool_return', 'sweep', 'drain']
lines = ['// Generated by tools/generate_proxy_profile.py from accepted exact-build evidence.',
         '// Source: ' + SOURCE, '#pragma once', '#include <cstdint>', '#include <cstddef>',
         'namespace pse::native_proxy::profile {',
         'struct Site { const char* name; std::uint32_t rva; unsigned char prefix[16]; };',
         'enum Index : std::size_t { ' + ', '.join(names) + ', Count };', 'inline constexpr Site Sites[] = {']
for name in names:
    s = sites[name]
    lines.append('    {"%s", 0x%x, {%s}},' % (name, s['rva'], ','.join('0x' + s['prefix'][i:i+2] for i in range(0,32,2))))
lines += ['};', '}']
(ROOT / 'experiments/pse_together/src/native/proxy_profile.hpp').write_text('\n'.join(lines) + '\n', encoding='utf8')
