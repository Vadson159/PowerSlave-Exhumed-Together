"""Build the John sprite package: one skin per player slot (8 players).

Additive KEX package: the 2015 rectangle/rotation definitions and the same four animations in a normal and a
"proxy" variant for every skin. Slot 0 (the host) is the original John (DOC-13 john.png, unmodified); slots 1..7 use
the same sheet with a coloured hat (docs/presentation/player_sprites/colored_hats/p2..p8.png). The proxy variant lowers
the origin by 59 texture pixels: the accepted passive proxy sits at authoritative z + 88 with scale 1.5 (59 * 1.5 =
88.5 world units). No actions, scripts or stock resource overrides.

Weapon icons (2026-11-21): the live proxy poses (idle, walk, shoot) also come with the icon of the weapon the player
holds above the head, one variant per weapon slot 0..7: player/pse_john[_pN]_proxy_{idle,walk,shoot}_w<W>. The icons
are the weapon wheel's own pictures (gfx/menu/menuweapon_<W>.png of the game), made smaller, with a thin light outline
and slightly translucent (docs/presentation/player_sprites/weapon_icons.png, rebuilt with --icons-from <the game's
PowerslaveEX.kpf>). They are an extra sprite layer of the same frames (sprites/player/pse_weapons): no actions either.

Resource names: player/pse_john[_pN]_{idle,walk,shoot,death} and player/pse_john[_pN]_proxy_{...}; slot S uses the
skin with N = S + 1 (slot 0 has no suffix). See player_animation.hpp resource().
"""
from pathlib import Path
import argparse
import hashlib
import io
import json
import math
import re
import zipfile

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'docs/presentation/player_sprites'
DEST = ROOT / 'experiments/pse_together/assets/coop_sprites_john.kpf'
NAME = 'pse_john'
HATS = SOURCE / 'colored_hats'
# (resource name, source sheet) in slot order: slot 0 = plain John, slot S = coloured hat pS+1.png.
SKINS = [(NAME, SOURCE / 'john.png')] + [(f'{NAME}_p{n}', HATS / f'p{n}.png') for n in range(2, 9)]
STATES = ('idle', 'walk', 'shoot', 'death')
LIVE_STATES = ('idle', 'walk', 'shoot')  # poses that carry the weapon icon (a dead player shows none)
ROTATIONS = ('N', 'NE', 'E', 'ES', 'S', 'SW', 'W', 'WN')
PROXY_DROP = 59
WEAPONS = 8
ICONS = SOURCE / 'weapon_icons.png'            # atlas: the 8 icons in one row (generated, see make_icons)
ICON_RECTS = SOURCE / 'weapon_icons_sprite.txt'  # their rectangles, KEX sprite syntax (generated with the atlas)
ICON_SHEET = 'pse_weapons'
ICON_GAP = 6  # texture pixels between the top of the head (highest live frame) and the bottom of the icon


def sha(b):
    return hashlib.sha256(b).hexdigest()


def make_icons(game_kpf, area=560.0, max_w=40, max_h=26, opacity=0.82, outline=(255, 232, 170), outline_alpha=0.62, pad=2):
    """Weapon wheel icons of the game (gfx/menu/menuweapon_0..7.png) -> one small atlas + rectangles.

    Each icon is cropped, scaled to about the same area (a long machete and a round grenade read the same size), with
    premultiplied alpha (no dark fringes), gets a 1 px light outline (the guns are black: unreadable on dark walls without
    it) and is made slightly translucent. Rectangles: one row, `pad` empty pixels around every icon.
    """
    from PIL import Image, ImageFilter
    with zipfile.ZipFile(game_kpf) as z:
        sources = [Image.open(io.BytesIO(z.read(f'gfx/menu/menuweapon_{i}.png'))).convert('RGBA') for i in range(WEAPONS)]
    icons = []
    for im in sources:
        im = im.crop(im.getbbox())
        w, h = im.size
        s = min(math.sqrt(area / (w * h)), max_w / w, max_h / h)
        nw, nh = max(1, round(w * s)), max(1, round(h * s))
        small = im.convert('RGBa').resize((nw, nh), Image.LANCZOS).convert('RGBA')
        canvas = Image.new('RGBA', (nw + 2, nh + 2), (0, 0, 0, 0))
        canvas.alpha_composite(small, (1, 1))
        ring = canvas.getchannel('A').point(lambda v: 255 if v > 40 else 0).filter(ImageFilter.MaxFilter(3))
        layer = Image.new('RGBA', canvas.size, outline + (0,))
        layer.putalpha(ring.point(lambda v: int(v * outline_alpha)))
        icon = Image.new('RGBA', canvas.size, (0, 0, 0, 0))
        icon.alpha_composite(layer)
        icon.alpha_composite(canvas)
        icon.putalpha(icon.getchannel('A').point(lambda v: int(v * opacity)))
        icons.append(icon)
    width = sum(i.width + 2 * pad for i in icons)
    height = max(i.height for i in icons) + 2 * pad
    atlas = Image.new('RGBA', (width, height), (0, 0, 0, 0))
    rects, x = [], 0
    for i in icons:
        atlas.alpha_composite(i, (x + pad, pad))
        rects.append((x + pad, pad, i.width, i.height))
        x += i.width + 2 * pad
    out = io.BytesIO()
    atlas.save(out, 'PNG', optimize=True)
    ICONS.write_bytes(out.getvalue())
    lines = ['// Weapon wheel icons (gfx/menu/menuweapon_0..7.png of the game), small, outlined, slightly translucent.',
             '// Generated by build_john_sprites.py --icons-from <PowerslaveEX.kpf>; index = weapon slot.',
             f'texture "sprites/player/{ICON_SHEET}.png"', '']
    lines += [f'sprite {i} {r[0]} {r[1]} {r[2]} {r[3]}' for i, r in enumerate(rects)]
    ICON_RECTS.write_text('\n'.join(lines) + '\n', encoding='utf8')
    return rects


def icon_rects():
    rects = [tuple(map(int, m)) for m in re.findall(r'^sprite\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)', ICON_RECTS.read_text(encoding='utf8'), re.M)]
    assert [r[0] for r in rects] == list(range(WEAPONS)), 'weapon_icons_sprite.txt: sprites 0..7'
    return {r[0]: r[1:] for r in rects}


def anim_block(text, anim):
    """The text of one animation (from its name line to the line before the next animation)."""
    start = re.search(rf'^{re.escape(anim)}\n', text, re.M)
    assert start, anim
    nxt = re.search(r'^\w+\n\{', text[start.end():], re.M)
    return text[start.start(): start.end() + nxt.start() if nxt else len(text)]


def icon_top(proxy_text, name):
    """y of the icon's bottom edge: ICON_GAP above the highest head of the live proxy frames of this skin."""
    tops = []
    for st in LIVE_STATES:
        block = anim_block(proxy_text, f'{name}_proxy_{st}')
        tops += [int(m) for m in re.findall(r'\{\s*"player/[^"]+",\s*\d+,\s*-?\d+,\s*(-?\d+),', block)]
    return min(tops) - ICON_GAP


def weapon_variants(proxy_text, name, rects):
    """Every live proxy animation once per weapon, with the icon as a second sprite layer of every rotation."""
    bottom = icon_top(proxy_text, name)
    out = [f'// {name}: proxy poses with the weapon icon above the head (generated by build_john_sprites.py)', '']
    for st in LIVE_STATES:
        block = anim_block(proxy_text, f'{name}_proxy_{st}').rstrip() + '\n'
        for w in range(WEAPONS):
            _, _, iw, ih = rects[w]
            layer = f'{{ "player/{ICON_SHEET}", {w}, {-(iw // 2)}, {bottom - ih}, 0 }}'
            variant = block.replace(f'{name}_proxy_{st}\n', f'{name}_proxy_{st}_w{w}\n', 1)
            # the frame's own sprite line is followed by the icon line, same indentation
            variant = re.sub(r'^(\s*)(\{\s*"player/' + re.escape(name) + r'",[^\n]*\})\n', lambda m: f'{m[1]}{m[2]}\n{m[1]}{layer}\n', variant, flags=re.M)
            out.append(variant)
    return '\n'.join(out)


def members():
    rects = (SOURCE / 'john_sprite.txt').read_text(encoding='utf8')
    anim = (SOURCE / 'john_anim.txt').read_text(encoding='utf8')
    icons = icon_rects()
    result = {}
    for name, sheet in SKINS:
        base = f'sprites/player/{name}'
        result[base + '.png'] = sheet.read_bytes()
        result[base + '_sprite.txt'] = rects.replace('player/john', f'player/{name}').encode()
        text = anim.replace('john_', name + '_').replace('player/john"', f'player/{name}"')
        result[base + '_anim.txt'] = text.encode()
        proxy = text.replace(name + '_', name + '_proxy_')
        proxy = re.sub(r'(,\s*-?\d+\s*,\s*)(-?\d+)(\s*,\s*[01]\s*})',
                       lambda m: m[1] + str(int(m[2]) + PROXY_DROP) + m[3], proxy)
        result[base + '_proxy_anim.txt'] = proxy.encode()
        result[base + '_proxy_weapons_anim.txt'] = weapon_variants(proxy, name, icons).encode()
    result[f'sprites/player/{ICON_SHEET}.png'] = ICONS.read_bytes()
    result[f'sprites/player/{ICON_SHEET}_sprite.txt'] = ICON_RECTS.read_bytes()
    result['PSE_TOGETHER_SPRITES_CREDITS.txt'] = (
        'John player sprites: PC Exhumed sprites ripped by Dunkelschwamm for The Spriters Resource.\n'
        'Source: supplied PowerSlave EX 2015 Co-Op Edition mods/john.kpf; DOC-13 assets.\n'
        'Original art belongs to its respective rights holders. Prior mod inclusion is not a new license.\n'
        'Slot 0 is the original John sheet; slots 1..7 are the same sheet with a coloured hat. No gameplay actions, scripts or stock overrides.\n'
        'Weapon icons above other players: the weapon wheel pictures of PowerSlave Exhumed (gfx/menu/menuweapon_0..7.png), scaled down,\n'
        'outlined and slightly translucent; they belong to their rights holders.\n'
    ).encode()
    return result


def validate(data):
    checks = [validate_skin(data, name, sheet) for name, sheet in SKINS]
    icons = validate_icons(data)
    return dict(skins=[c['skin'] for c in checks], rectangles=40, frames=14, pixels_unchanged=True,
                weapon_icon_animations=sum(c['weapon_animations'] for c in checks), weapon_icons=icons)


def validate_icons(data):
    from PIL import Image
    im = Image.open(io.BytesIO(data[f'sprites/player/{ICON_SHEET}.png'])).convert('RGBA')
    text = data[f'sprites/player/{ICON_SHEET}_sprite.txt'].decode()
    assert f'texture "sprites/player/{ICON_SHEET}.png"' in text
    rects = [tuple(map(int, m)) for m in re.findall(r'^sprite\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)', text, re.M)]
    assert [r[0] for r in rects] == list(range(WEAPONS))
    for _, x, y, w, h in rects:
        assert 0 < w <= 48 and 0 < h <= 32 and x + w <= im.width and y + h <= im.height
        assert im.crop((x, y, x + w, y + h)).getchannel('A').getextrema()[1] > 0  # not empty
    assert im.getchannel('A').getextrema()[1] <= 230  # slightly translucent everywhere
    return dict(size=im.size, rects=[r[1:] for r in rects])


def validate_skin(data, NAME, sheet):
    from PIL import Image
    base = f'sprites/player/{NAME}'
    master = Image.open(sheet).convert('RGBA')
    im = Image.open(io.BytesIO(data[base + '.png'])).convert('RGBA')
    assert im.size == (1024, 315) and list(im.getdata()) == list(master.getdata())
    rects = [tuple(map(int, m)) for m in re.findall(r'^sprite\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)',
                                                    data[base + '_sprite.txt'].decode(), re.M)]
    assert [r[0] for r in rects] == list(range(40))
    assert all(w > 0 and h > 0 and x + w <= im.width and y + h <= im.height for _, x, y, w, h in rects)
    assert f'texture "{base}.png"' in data[base + '_sprite.txt'].decode()
    for suffix, proxy in (('_anim.txt', False), ('_proxy_anim.txt', True)):
        text = data[base + suffix].decode()
        tokens = re.findall(r'"[^"]*"|-?\d+|[A-Za-z_][A-Za-z_0-9]*|[{},]', re.sub(r'//[^\n]*', '', text))
        names = {f'{NAME}_{"proxy_" if proxy else ""}{s}' for s in STATES}
        allowed = names | {'frame', 'delay', 'sprites'} | {'rotation_' + r for r in ROTATIONS}
        # Whitelisted grammar: no actions, jumps, Remove or script callbacks.
        assert all(t in allowed or t in '{} ,' or re.fullmatch(r'-?\d+', t) or t == f'"player/{NAME}"' for t in tokens)
        assert set(re.findall(rf'^{NAME}_\w+', text, re.M)) == names
        assert len(re.findall(r'\bframe\b', re.sub(r'//[^\n]*', '', text))) == 14
        for rot in ROTATIONS:
            assert text.count('rotation_' + rot + '\n') == 14
        assert 'delay 65535' in text and 'john' not in text.replace(NAME, '')
        assert all(0 <= int(s) < 40 for s in re.findall(r'\{\s*"[^"]+",\s*(\d+)', text))
    # Weapon variants: the same grammar, 3 live poses x 8 weapons, every rotation of every frame = the John layer + exactly one icon layer.
    text = data[base + '_proxy_weapons_anim.txt'].decode()
    clean = re.sub(r'//[^\n]*', '', text)
    tokens = re.findall(r'"[^"]*"|-?\d+|[A-Za-z_][A-Za-z_0-9]*|[{},]', clean)
    names = {f'{NAME}_proxy_{s}_w{w}' for s in LIVE_STATES for w in range(WEAPONS)}
    allowed = names | {'frame', 'delay', 'sprites'} | {'rotation_' + r for r in ROTATIONS}
    assert all(t in allowed or t in '{} ,' or re.fullmatch(r'-?\d+', t) or t in (f'"player/{NAME}"', f'"player/{ICON_SHEET}"') for t in tokens)
    assert set(re.findall(rf'^{NAME}_\w+', text, re.M)) == names
    frames_per = {'idle': 1, 'walk': 4, 'shoot': 2}
    assert len(re.findall(r'\bframe\b', clean)) == WEAPONS * sum(frames_per.values())
    for st in LIVE_STATES:
        for w in range(WEAPONS):
            block = anim_block(text, f'{NAME}_proxy_{st}_w{w}')
            assert block.count('frame') == frames_per[st] and 'delay 65535' not in block
            assert len(re.findall(rf'"player/{ICON_SHEET}", {w},', block)) == frames_per[st] * len(ROTATIONS)
            assert len(re.findall(rf'"player/{NAME}",', block)) == frames_per[st] * len(ROTATIONS)
            assert not re.search(rf'"player/{ICON_SHEET}", (?!{w},)', block)
    return dict(skin=NAME, texture=base + '.png', pixels_unchanged=True, rectangles=40, frames=14, weapon_animations=len(names))


def build(path=DEST):
    data = members()
    check = validate(data)
    path = Path(path).resolve()
    if not path.is_relative_to(ROOT):
        raise ValueError('Output outside mod workspace')
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name, value in sorted(data.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 11, 7, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            z.writestr(info, value, compresslevel=9)
    manifest = dict(schema='pse-p8-john-hats-v2', package=path.relative_to(ROOT).as_posix(),
                    sha256=sha(path.read_bytes()), character=NAME, scale=1.5, proxy_origin_drop=PROXY_DROP,
                    slots=[dict(slot=i, character=name) for i, (name, _) in enumerate(SKINS)], check=check,
                    members=[dict(path=n, sha256=sha(b), size=len(b)) for n, b in sorted(data.items())],
                    source=[dict(path=p.relative_to(ROOT).as_posix(), sha256=sha(p.read_bytes()))
                            for p in [s for _, s in SKINS] + [SOURCE / 'john_anim.txt', SOURCE / 'john_sprite.txt', ICONS, ICON_RECTS]],
                    runtime_verified=False)
    path.with_suffix('.manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf8')
    return manifest


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', type=Path, default=DEST)
    ap.add_argument('--icons-from', type=Path, help="the game's PowerslaveEX.kpf: rebuild weapon_icons.png / weapon_icons_sprite.txt first")
    args = ap.parse_args()
    if args.icons_from:
        print('weapon icons:', make_icons(args.icons_from))
    m = build(args.out)
    print(f'JOHN SKINS ({len(SKINS)}): {len(m["members"])} members; weapon icon animations '
          f'{m["check"]["weapon_icon_animations"]}; sha256={m["sha256"]}')
