"""Compile new P8 expedition atlases into KEX metadata without editing PNG pixels.

Reads alpha only to bound each of the 40 grid cells. Keeps the ImageGen PNGs
byte-identical, generates sprite rectangles/origins and scale hints, and reuses
only the documented animation timing/direction map (no John bitmap pixels).
"""
from pathlib import Path
import hashlib
import json
import re
import statistics
import zipfile
from PIL import Image

ROOT=Path(__file__).resolve().parents[3]
LAB=ROOT/'experiments/pse_together'
ART=LAB/'assets/alternatives'
DEST=LAB/'assets/coop_sprites_expedition.kpf'
NAMES=('expedition_ranger','ruins_scout')
def sha(b):return hashlib.sha256(b).hexdigest()

def build():
    template=(ROOT/'docs/presentation/player_sprites/john_anim.txt').read_text()
    template=re.sub(r'//[^\n]*','',template)
    members={};profiles=[]
    for name in NAMES:
        path=ART/(name+'_v1.png');im=Image.open(path).convert('RGBA')
        assert im.width>1000 and im.height>600
        alpha=im.getchannel('A');boxes=[];anchors=[]
        for i in range(40):
            col,row=i%8,i//8
            x0,x1=round(col*im.width/8),round((col+1)*im.width/8)
            y0,y1=round(row*im.height/5),round((row+1)*im.height/5)
            # Analysis mask only. No pixels are rewritten: original atlas bytes
            # remain in the KPF. Ignore near-transparent matting noise for bounds.
            box=alpha.crop((x0,y0,x1,y1)).point(lambda a:255 if a>=128 else 0).getbbox()
            assert box is not None,(name,i)
            l,t,r,b=box;w,h=r-l,b-t;assert w>15 and h>15
            boxes.append((x0+l,y0+t,w,h))
            anchors.append((round((x1-x0)/2)-l,h))
        scale=round(150.0/statistics.median(b[3] for b in boxes[:25]),6)
        assert .5<scale<1.5
        rects='texture "sprites/player/'+name+'.png"\n\n'
        rects+='\n'.join(f'sprite {i} {x} {y} {w} {h}' for i,(x,y,w,h) in enumerate(boxes))+'\n'
        members[f'sprites/player/{name}.png']=path.read_bytes()
        members[f'sprites/player/{name}_sprite.txt']=rects.encode()
        for proxy in (False,True):
            anim=template.replace('john_',name+('_proxy_' if proxy else '_'))
            def entry(m):
                i,flip=int(m[1]),int(m[4]);x,y=anchors[i];w=boxes[i][2]
                x=-(w-x) if flip else -x
                y=-y+(round(88/scale) if proxy else 0)
                return f'{{ "player/{name}", {i}, {x}, {y}, {flip} }}'
            anim=re.sub(r'\{\s*"player/john",\s*(\d+),\s*(-?\d+),\s*(-?\d+),\s*([01])\s*}',entry,anim)
            assert anim.count('frame\n')==14 and 'player/john' not in anim
            assert not re.search(r'\b(actions|action|goto|script|remove)\b',anim,re.I)
            suffix='_proxy_anim.txt' if proxy else '_anim.txt'
            members[f'sprites/player/{name}'+suffix]=anim.encode()
        profiles.append(dict(name=name,width=im.width,height=im.height,scale=scale,
                             sha256=sha(path.read_bytes()),rectangles=boxes,anchors=anchors,
                             alpha_threshold_for_bounds=128,source_pixels_unchanged=True))
    members['PSE_EXPEDITION_CREDITS.txt']=(
        'New expedition character atlases generated with the built-in OpenAI ImageGen tool, 2026-11-04.\n'
        'Prompts and original PNGs: experiments/pse_together/assets/alternatives/.\n'
        'Timing/direction map based on DOC-13 john_anim.txt; no John bitmap pixels included.\n'
        'Candidates for visual review; no claim of hand-authored or perfectly consistent animation.\n').encode()
    with zipfile.ZipFile(DEST,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for name,value in sorted(members.items()):
            info=zipfile.ZipInfo(name,(2026,11,4,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o100644<<16
            z.writestr(info,value,compresslevel=9)
    manifest=dict(schema='pse-p8-expedition-v1',sha256=sha(DEST.read_bytes()),profiles=profiles,
                  slots=[dict(slot=i,character=NAMES[i%2]) for i in range(8)],
                  members=[dict(path=n,size=len(b),sha256=sha(b)) for n,b in sorted(members.items())],runtime_verified=False)
    DEST.with_suffix('.manifest.json').write_text(json.dumps(manifest,indent=2))
    header='#pragma once\n// Generated by build_expedition_sprites.py; source PNG pixels are unchanged.\n'
    header+='namespace pse::player_art {\ninline constexpr float ExpeditionScales[2]={'
    header+=','.join(str(p['scale'])+'f' for p in profiles)+'};\n}\n'
    (LAB/'src/native/expedition_profile.hpp').write_text(header)
    print(json.dumps(dict(package=str(DEST),sha256=manifest['sha256'],profiles=[{k:p[k] for k in ['name','width','height','scale']} for p in profiles])))
    return manifest
if __name__=='__main__':build()
